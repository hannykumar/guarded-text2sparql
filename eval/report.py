"""Build results/RESULTS.md from the committed metrics JSON.

Reads results/<config>/<split>/run<n>/metrics.json and results/diagnostics.json.
Reports mean and range over runs, because local inference is not bit-identical.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from statistics import mean

RESULTS = Path("results")
SPLIT_NOTES = {
    "dev": "The 15 questions used while building the system.",
    "test": "The 35 questions held back until the design was frozen. **These are the honest numbers.**",
    "ck26": "CK26: the same graph with the questions reworded (49 of 50 reference queries are "
            "identical to CK25's). A paraphrase-robustness check, not a held-out set.",
}
LABELS = {
    "A0": "LLM only",
    "A1": "+ schema card",
    "A2": "+ entity linking",
    "A3": "+ guardrails and repair",
}


def scores(path: Path) -> dict[str, float]:
    """Average metrics of one run, plus how many questions matched exactly."""
    data = json.loads(path.read_text())
    questions = {k: v for k, v in data.items() if k.startswith(("ck25:", "ck26:"))}
    average = data.get("average", {})
    return {
        "f1": average.get("set_F", 0.0),
        "precision": average.get("set_P", 0.0),
        "recall": average.get("set_recall", 0.0),
        "exact": sum(1 for v in questions.values() if v.get("set_F", 0) > 0.99),
        "questions": len(questions),
    }


def collect() -> dict[tuple[str, str], list[dict]]:
    runs: dict[tuple[str, str], list[dict]] = {}
    for metrics in sorted(Path(RESULTS).glob("*/*/run*/metrics.json")):
        config, split = metrics.relative_to(RESULTS).parts[:2]
        runs.setdefault((config, split), []).append(scores(metrics))
    return runs


def cell(values: list[float]) -> str:
    """Mean, with the range when runs disagree."""
    if not values:
        return "-"
    if len(values) == 1 or max(values) - min(values) < 0.005:
        return f"{mean(values):.3f}"
    return f"{mean(values):.3f} ({min(values):.3f}-{max(values):.3f})"


def table(runs: dict[tuple[str, str], list[dict]], split: str) -> list[str]:
    rows = [f"### {split}", "", SPLIT_NOTES.get(split, ""), "", "| Config | What it adds | F1 | Precision | Recall | Exact | Runs |", "|---|---|---|---|---|---|---|"]
    present = [(c, s) for (c, s) in runs if s == split]
    if not present:
        return [f"### {split}", "", "_not run yet_", ""]
    for config in sorted({c for c, _ in present}):
        values = runs[(config, split)]
        exact = f"{mean(v['exact'] for v in values):.1f}/{values[0]['questions']}"
        rows.append(
            f"| {config} | {LABELS.get(config, '')} | {cell([v['f1'] for v in values])} | "
            f"{cell([v['precision'] for v in values])} | {cell([v['recall'] for v in values])} | {exact} | {len(values)} |"
        )
    return [*rows, ""]


def diagnostics_table() -> list[str]:
    path = RESULTS / "diagnostics.json"
    if not path.exists():
        return []
    data = json.loads(path.read_text())
    rows = [
        "## Guardrail diagnostics",
        "",
        "From the pipeline's own traces, not from the reference answers.",
        "",
        "| Config | Questions | Clean first try | Needed repair | Repair worked | Pass at end | G1 blocks | p50 s | p95 s |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for config, summary in sorted(data.items()):
        if not summary:
            continue
        rate = summary.get("repair_success_rate")
        rows.append(
            f"| {config} | {summary['questions']} | {summary['clean_first_try']} | {summary['needed_repair']} | "
            f"{summary['repair_succeeded']}{f' ({rate:.0%})' if rate is not None else ''} | "
            f"{summary['passing_all_guardrails_at_the_end']} | {summary['g1_blocks']} | "
            f"{summary['seconds_p50']} | {summary['seconds_p95']} |"
        )
    first_failures = {c: s.get("first_failure_by_guardrail") for c, s in data.items() if s}
    if any(first_failures.values()):
        rows += ["", "First guardrail to fire, per config: `" + json.dumps(first_failures) + "`", ""]
    return [*rows, ""]


def main() -> int:
    runs = collect()
    lines = [
        "# Results",
        "",
        "Generated by `eval/report.py`. Scores come from the official `text2sparql` client:",
        "it executes our query and the reference query and compares the result sets.",
        "",
        "## Ablation",
        "",
    ]
    # whichever splits were actually measured, in a sensible reading order
    order = ["dev", "test", "all", "ck26"]
    found = sorted({s for _, s in runs}, key=lambda s: order.index(s) if s in order else 99)
    if not found:
        lines += ["_No measurements yet._", ""]
    for split in found:
        lines += table(runs, split)
    lines += diagnostics_table()
    lines += [
        "## How to read this",
        "",
        "- **dev** is the 15 questions used while building. **test** is the 35 held back until the design was frozen.",
        "  The test numbers are the honest ones; dev is shown because the design was tuned against it.",
        "- **Exact** counts questions whose result set matched the reference completely.",
        "- Each configuration runs three times; the range is shown when runs disagree.",
        "",
    ]
    (RESULTS / "RESULTS.md").write_text("\n".join(lines))
    print(f"wrote {RESULTS / 'RESULTS.md'} ({len(runs)} config/split combinations)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
